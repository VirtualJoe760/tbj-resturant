// `create-tbj-restaurant store`: the files that turn the site into Play Store and App Store apps.
// Android: a Trusted Web Activity (the site full-screen in Chrome) built with Bubblewrap.
// iPhone: a Capacitor shell that loads the site, built in Xcode on a Mac or a cloud Mac.
// Both read name, colors and icons from the live site's manifest, which comes from business-theme.ts.
import fs from "node:fs";
import path from "node:path";

export interface StoreInput {
  name: string;
  shortName: string;
  url: string; // https://… the live (or demo) site
  androidPackage: string; // com.example.app
  iosBundleId: string;
  themeColor: string;
  backgroundColor: string;
}

/** "thehoodpalmdesert.com" → "com.thehoodpalmdesert.app" (letters and digits only per segment). */
export function packageIdFor(domain: string) {
  const parts = domain.toLowerCase().replace(/^www\./, "").split(".").reverse().map((p) => p.replace(/[^a-z0-9]/g, "")).filter(Boolean);
  if (/^\d/.test(parts[1] ?? "")) parts[1] = `x${parts[1]}`;
  return [...parts, "app"].join(".");
}

export function writeStoreKit(dir: string, s: StoreInput) {
  fs.mkdirSync(dir, { recursive: true });
  const host = new URL(s.url).host;
  const write = (f: string, data: unknown) => fs.writeFileSync(path.join(dir, f), typeof data === "string" ? data : JSON.stringify(data, null, 2) + "\n");

  // Bubblewrap reads this to generate and sign the Android project (`bubblewrap build`).
  write("twa-manifest.json", {
    packageId: s.androidPackage, host, name: s.name, launcherName: s.shortName, display: "standalone", orientation: "portrait",
    themeColor: s.themeColor, navigationColor: s.themeColor, backgroundColor: s.backgroundColor, enableNotifications: true,
    startUrl: "/", iconUrl: `${s.url}/icon-512`, maskableIconUrl: `${s.url}/icon-maskable`, webManifestUrl: `${s.url}/manifest.webmanifest`,
    appVersionName: "1.0.0", appVersionCode: 1, signingKey: { path: "./android.keystore", alias: "android" },
    fallbackType: "customtabs", splashScreenFadeOutDuration: 300, minSdkVersion: 21, shortcuts: [],
  });

  // Capacitor wraps the live site for iPhone (`npx cap add ios`, then open in Xcode).
  write("capacitor.config.json", {
    appId: s.iosBundleId, appName: s.shortName, webDir: "www",
    server: { url: s.url, cleartext: false },
    ios: { contentInset: "always", backgroundColor: s.backgroundColor },
  });
  fs.mkdirSync(path.join(dir, "www"), { recursive: true });
  write("www/index.html", `<!doctype html><meta http-equiv="refresh" content="0;url=${s.url}"><title>${s.shortName}</title>\n`);

  write("README.md", `# ${s.name}: app-store kit

Generated by \`create-tbj-restaurant store\`. The apps load ${s.url}, so menu, prices, photos
and branding update without resubmitting. Name, colors and icons come from the site, which reads
\`src/config/business-theme.ts\`. Full walkthrough: docs/16-app-stores.md.

## Google Play (works from Windows)
1. \`npm i -g @bubblewrap/cli\`, then in this folder: \`bubblewrap build\` (first run installs the Android tools and makes \`android.keystore\`; keep that file and its password safe — every update must be signed with it).
2. \`bubblewrap fingerprint\` prints the signing fingerprint. Put it in \`src/config/restaurant.ts\` → \`app.androidSha256\` and deploy; ${s.url}/.well-known/assetlinks.json then proves the app and site belong together (no browser bar in the app).
3. Upload \`app-release-bundle.aab\` in Play Console (package \`${s.androidPackage}\`).

## Apple App Store (needs a Mac, or a cloud Mac such as Codemagic)
1. \`npm i @capacitor/core @capacitor/cli @capacitor/ios && npx cap add ios && npx cap open ios\`
2. In Xcode set the team, the bundle id \`${s.iosBundleId}\`, and the icon (download ${s.url}/icon-512, Apple wants 1024 × 1024 with no transparency).
3. Put \`<team id>.${s.iosBundleId}\` in \`src/config/restaurant.ts\` → \`app.iosAppId\` and deploy, so links open the app.
4. Apple rejects apps that are "just a website": ship with push notifications for order-ready alerts and Sign in with Apple before submitting (docs/16-app-stores.md).
`);
}
