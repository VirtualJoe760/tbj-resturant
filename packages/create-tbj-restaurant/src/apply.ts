// Points the demo app in this repo at a new business: regenerates src/config/restaurant.ts and
// src/config/business-theme.ts (+ public/brand/ images), loads the intake into the database
// (local or Neon), and optionally commits + pushes so Vercel redeploys the preview site.
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import type { Intake } from "./types.ts";
import { installTheme } from "./theme.ts";
import { packageIdFor } from "./store.ts";

const STATE_TZ: Record<string, string> = {
  CA: "America/Los_Angeles", OR: "America/Los_Angeles", WA: "America/Los_Angeles", NV: "America/Los_Angeles",
  AZ: "America/Phoenix", CO: "America/Denver", UT: "America/Denver", NM: "America/Denver", MT: "America/Denver", ID: "America/Boise", WY: "America/Denver",
  TX: "America/Chicago", IL: "America/Chicago", MN: "America/Chicago", MO: "America/Chicago", WI: "America/Chicago", LA: "America/Chicago", OK: "America/Chicago",
  KS: "America/Chicago", NE: "America/Chicago", IA: "America/Chicago", AR: "America/Chicago", MS: "America/Chicago", AL: "America/Chicago", TN: "America/Chicago",
  HI: "Pacific/Honolulu", AK: "America/Anchorage",
};

export function timezoneFor(address = "") {
  const st = address.match(/,\s*([A-Z]{2})\s+\d{5}/)?.[1] ?? address.match(/,\s*([A-Z]{2})\b/)?.[1];
  return (st && STATE_TZ[st]) || (st ? "America/New_York" : "America/Los_Angeles");
}

export function shortNameOf(name: string) {
  if (name.length <= 16) return name;
  const cut = name.split(/\s+(?:Bar\b|Restaurant\b|Grill\b|Pizzeria\b|Pizza\b|Cafe\b|Kitchen\b|Diner\b|Tavern\b|Cantina\b|&|and\b|-)/i)[0].trim();
  return cut.length >= 3 ? cut : name.split(/\s+/).slice(0, 2).join(" ");
}

export function domainFor(intake: Intake) {
  if (intake.website) {
    try {
      return new URL(intake.website).hostname.replace(/^www\./, "");
    } catch {}
  }
  return `${intake.slug.replace(/-/g, "")}.com`;
}

const q = (s: string) => JSON.stringify(s);

export function configSource(intake: Intake) {
  const short = shortNameOf(intake.name);
  const f = intake.features;
  const links = Object.entries(intake.links).filter(([, v]) => v).map(([k, v]) => `${k}: ${q(v!)}`).join(", ");
  const d = intake.delivery;
  const delivery = d
    ? `\n  delivery: { enabled: ${d.enabled}, provider: ${q(d.provider)}, customerFee: ${d.customerFee === "quote" ? q("quote") : d.customerFee}, minOrderCents: ${d.minOrderCents} },`
    : "";
  const app = { androidPackage: intake.app?.androidPackage ?? packageIdFor(domainFor(intake)), iosBundleId: intake.app?.iosBundleId };
  return `// The current restaurant. Generated by \`create-tbj-restaurant switch\` (packages/create-tbj-restaurant);
// edit by hand only for the live client repo. The look (logo, icon, banners, fonts, colors)
// is in business-theme.ts. See docs/15-intake-and-demo.md.
import type { RestaurantConfig } from "./types";

export { APP_MODE, isDemo } from "./types";
export type { RestaurantConfig } from "./types";

export const restaurant: RestaurantConfig = {
  slug: ${q(intake.slug)},
  name: ${q(intake.name)},
  shortName: ${q(short)},
  tagline: ${q(intake.cuisine ? `${intake.cuisine} · order online for pickup` : "Order online for pickup")},
  domain: ${q(domainFor(intake))},
  timezone: ${q(intake.timezone)},
  address: ${q(intake.address ?? "")},
  phone: ${q(intake.phone ?? "")},
  location: { lat: ${intake.location?.lat ?? 0}, lng: ${intake.location?.lng ?? 0} },
  payments: { mode: "connect" },
  features: { voice: ${!!f.voice}, newsletter: ${f.newsletter !== false}, events: ${f.events !== false}, scheduling: ${f.scheduling !== false}, payroll: false, deposits: true },
  social: [],
  links: { ${links} },${delivery}
  app: { androidPackage: ${q(app.androidPackage)}${app.iosBundleId ? `, iosBundleId: ${q(app.iosBundleId)}` : ""} },
};
`;
}

/** Finds the app root (the folder with src/config/restaurant.ts) from the current directory upward. */
export function findAppRoot(start = process.cwd()) {
  let dir = start;
  for (let i = 0; i < 6; i++) {
    if (fs.existsSync(path.join(dir, "src", "config", "restaurant.ts"))) return dir;
    dir = path.dirname(dir);
  }
  return null;
}

export interface ApplyOptions {
  root: string;
  clientsDir: string;
  deploy: boolean; // commit + push so Vercel rebuilds (and loads the business into Neon)
  skipImport?: boolean; // don't load into the local embedded database
}

export function applyToApp(intake: Intake, opts: ApplyOptions): string[] {
  const log: string[] = [];
  const shortName = shortNameOf(intake.name);
  const domain = domainFor(intake);
  // the importer reads these to rename pages and test accounts
  const intakeFile = path.join(opts.clientsDir, intake.slug, "intake.json");
  fs.writeFileSync(intakeFile, JSON.stringify({ ...intake, shortName, domain }, null, 2));

  fs.writeFileSync(path.join(opts.root, "src", "config", "restaurant.ts"), configSource(intake));
  log.push(`Updated src/config/restaurant.ts → ${intake.name}`);
  fs.writeFileSync(path.join(opts.root, "src", "config", "business-theme.ts"), installTheme(intake, path.join(opts.clientsDir, intake.slug), opts.root));
  log.push("Updated src/config/business-theme.ts and public/brand/ (logo, app icon, banners, fonts, colors)");

  if (!opts.skipImport) {
    // local embedded database (stop `pnpm dev` first); DATABASE_URL in the shell targets that database instead
    const r = spawnSync("pnpm", ["import-client", intake.slug], { cwd: opts.root, env: { ...process.env, CR_OUT: opts.clientsDir }, stdio: "inherit", shell: process.platform === "win32" });
    if (r.status !== 0) throw new Error("Loading the business into the database failed (see output above)");
    log.push(`Loaded menu, hours and address into the local database; test accounts are now @${domain}`);
  }

  if (opts.deploy) {
    const git = (...args: string[]) => spawnSync("git", args, { cwd: opts.root, stdio: "inherit" });
    git("add", "-A", "src/config/restaurant.ts", "src/config/business-theme.ts", "public/brand", path.relative(opts.root, path.join(opts.clientsDir, intake.slug)));
    git("commit", "-m", `Switch demo to ${intake.name}`);
    const push = git("push");
    if (push.status !== 0) throw new Error("git push failed");
    log.push("Pushed — Vercel is rebuilding the preview site");
  }
  return log;
}
